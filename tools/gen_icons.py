"""Replace FongMi's UI glyphs with Material Symbols Rounded (filled), the closest open match to
SF Symbols (as Aerial does; SF Symbols may only be used on Apple platforms).

Material Symbols: Apache 2.0, https://github.com/google/material-design-icons (NOTICE-material-symbols.txt).
Writes skin/res/drawable[-anydpi]/<upstream name>.xml. PNG-backed upstream icons (drawable-*dpi)
are replaced through drawable-anydpi, which takes precedence over density-specific folders.

    python -I tools/gen_icons.py --base work/<version>-<abi>/base/res
"""

import argparse
import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "skin" / "res"
URL = "https://raw.githubusercontent.com/google/material-design-icons/master/symbols/android/{n}/materialsymbolsrounded/{n}_{v}.xml"
CACHE = ROOT / "work" / "symbols"

# upstream drawable -> (symbol, filled)
ICONS = {
    "ic_home_vod": ("smart_display", True),
    "ic_home_live": ("sensors", True),
    "ic_home_search": ("search", True),
    "ic_home_keep": ("favorite", True),
    "ic_home_setting": ("settings", True),
    "ic_home_connect": ("devices", True),
    "ic_detail_desc": ("info", True),
    "ic_detail_keep_off": ("favorite", False),
    "ic_detail_keep_on": ("favorite", True),
    "ic_detail_change": ("swap_horiz", True),
    "ic_setting_home": ("home", True),
    "ic_setting_history": ("history", True),
    "ic_setting_refresh": ("refresh", True),
    "ic_setting_delete": ("delete", True),
}


def symbol(name, filled):
    CACHE.mkdir(parents=True, exist_ok=True)
    v = "fill1_24px" if filled else "24px"
    f = CACHE / f"{name}_{v}.xml"
    if not f.exists():
        urllib.request.urlretrieve(URL.format(n=name, v=v), f)
    return f.read_text(encoding="utf-8")


def upstream(base, name):
    """(folder, size in dp) of the upstream drawable, so ours lands where it wins and keeps its size."""
    vec = base / "drawable" / f"{name}.xml"
    if vec.exists():
        size = re.search(r'android:width="([\d.]+)dp"', vec.read_text(encoding="utf-8"))
        return "drawable", size.group(1) if size else "24.0"
    if list(base.glob(f"drawable-*dpi/{name}.png")):
        return "drawable-anydpi", "36.0"
    raise SystemExit(f"{name}: not found upstream")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", required=True, help="decoded upstream res dir")
    base = Path(ap.parse_args().base)
    for name, (sym, filled) in ICONS.items():
        folder, size = upstream(base, name)
        xml = symbol(sym, filled)
        xml = re.sub(r'android:width="[^"]*"', f'android:width="{size}dp"', xml)
        xml = re.sub(r'android:height="[^"]*"', f'android:height="{size}dp"', xml)
        xml = xml.replace('android:tint="?attr/colorControlNormal"', 'android:tint="@color/white"')
        out = RES / folder / f"{name}.xml"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text('<?xml version="1.0" encoding="utf-8"?>\n'
                       f"<!-- GENERATED by tools/gen_icons.py: Material Symbols Rounded '{sym}'"
                       f"{' (filled)' if filled else ''}, Apache 2.0. -->\n" + xml.strip() + "\n", encoding="utf-8")
        print(f"{folder}/{name}: {sym}")


if __name__ == "__main__":
    main()
