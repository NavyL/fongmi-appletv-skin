"""Write the tvOS state selectors (skin/res/drawable/selector_tvos_*.xml) and press animators.

tvOS focusable items have five states (HIG, Focus and selection): unfocused, focused, pressed
(brief feedback when chosen), selected (current), unavailable. One table drives every selector so
the states stay consistent.

    python -I tools/gen_selectors.py
"""

from pathlib import Path

RES = Path(__file__).resolve().parent.parent / "skin" / "res"
NS = 'xmlns:android="http://schemas.android.com/apk/res/android"'

# name: (corner radius, rest fill)  -- focused/pressed/selected/disabled fills are shared
SHAPES = {
    "pill": ("100.0dp", "@color/tvos_control"),
    "button": ("100.0dp", "@color/tvos_control"),   # like pill, but ignores "selected" (marquee titles use it)
    "tile": ("8.0dp", "@color/tvos_control"),
    "key": ("8.0dp", "@color/tvos_glass_rest"),
    "row": ("8.0dp", None),                            # rows over video: clear at rest
}
PRESSED = "#FFD4D4D8"   # the white plate dips to light grey while OK is held


def shape(fill, radius):
    return (f'        <shape android:shape="rectangle">\n'
            f'            <solid android:color="{fill}" />\n'
            f'            <corners android:radius="{radius}" />\n'
            f'        </shape>\n')


def selector(name, radius, rest):
    items = [
        ('android:state_enabled="false"', "@color/tvos_disabled_fill" if rest else None),
        ('android:state_focused="true" android:state_pressed="true"', PRESSED),
        ('android:state_focused="true"', "@color/tvos_focus"),
    ]
    if name != "button":
        items.append(('android:state_selected="true"', "@color/tvos_selected"))
    out = [f'<?xml version="1.0" encoding="utf-8"?>\n<!-- GENERATED by tools/gen_selectors.py: tvOS {name} '
           f'(disabled / pressed / focused / current / rest). -->\n<selector {NS}>\n']
    for state, fill in items:
        if fill is None:
            out.append(f'    <item {state} android:drawable="@android:color/transparent" />\n')
        else:
            out.append(f'    <item {state}>\n{shape(fill, radius)}    </item>\n')
    out.append(f'    <item>\n{shape(rest, radius)}    </item>\n' if rest
               else '    <item android:drawable="@android:color/transparent" />\n')
    out.append('</selector>\n')
    (RES / "drawable" / f"selector_tvos_{name}.xml").write_text("".join(out), encoding="utf-8")


def press_animator(name, focus_scale, comment):
    def scale(state, value, ms, interp):
        return (f'    <item {state}>\n        <set>\n'
                f'            <objectAnimator android:propertyName="scaleX" android:valueTo="{value}" android:duration="{ms}" android:interpolator="{interp}" android:valueType="floatType" />\n'
                f'            <objectAnimator android:propertyName="scaleY" android:valueTo="{value}" android:duration="{ms}" android:interpolator="{interp}" android:valueType="floatType" />\n'
                f'        </set>\n    </item>\n')
    dec = "@android:interpolator/decelerate_cubic"
    body = (scale('android:state_focused="true" android:state_pressed="true"', 0.96, 90, dec)
            + scale('android:state_focused="true"', focus_scale, 180, dec)
            + scale("", 1.0, 140, "@android:interpolator/decelerate_quad").replace("<item >", "<item>"))
    (RES / "animator" / f"{name}.xml").write_text(
        f'<?xml version="1.0" encoding="utf-8"?>\n<!-- GENERATED by tools/gen_selectors.py: {comment} -->\n'
        f"<selector {NS}>\n{body}</selector>\n", encoding="utf-8")


if __name__ == "__main__":
    for name, (radius, rest) in SHAPES.items():
        selector(name, radius, rest)
    press_animator("tvos_press", 1.05, "chips/keys/buttons grow a little with focus, dip when pressed (Yingxia chip 1.06)")
    press_animator("tvos_press_tile", 1.02, "wide rows/tiles: a gentler lift (Yingxia rows 1.02)")
    press_animator("tvos_press_flat", 1.0, "rows that must not grow (live guide): only the press dip")
    print("ok")
