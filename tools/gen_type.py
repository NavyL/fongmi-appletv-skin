"""Point Material 3's type scale at Inter (skin/res/values/styles_m3type.xml).

Dialogs, sheets and Material buttons take their text from TextAppearance.M3.Sys.Typescale.*,
which name Roboto ("sans-serif", "sans-serif-medium") directly, so the theme font alone does not
reach them. This copies upstream's definitions and swaps the family/weight: regular -> Inter 500
(tvOS text is Medium), medium -> Inter 600; Display/Headline use the Display cut. Tracking is
tightened for Inter (M3's values are tuned for Roboto).

build.py runs this on every build. Standalone: python -I tools/gen_type.py --base work/<version>-<abi>/base/res
"""

import argparse
import copy
import xml.etree.ElementTree as ET
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "skin" / "res" / "values" / "styles_m3type.xml"
PREFIX = "TextAppearance.M3.Sys.Typescale."
WEIGHT = {"@string/m3_ref_typeface_plain_regular": "500", "@string/m3_ref_typeface_brand_regular": "500",
          "@string/m3_ref_typeface_plain_medium": "600", "@string/m3_ref_typeface_brand_medium": "600"}


def generate(base, quiet=False):
    """base: decoded upstream res dir."""
    base = Path(base)
    out = ET.Element("resources")
    for style in ET.parse(base / "values" / "styles.xml").getroot():
        name = style.get("name", "")
        if style.tag != "style" or not name.startswith(PREFIX):
            continue
        family = "@font/tvos_display" if any(k in name for k in ("Display", "Headline")) else "@font/tvos_text"
        new = copy.deepcopy(style)
        weight = None
        for item in new:
            key = item.get("name")
            if key in ("android:fontFamily", "fontFamily"):
                weight = WEIGHT.get(item.text, weight)
                item.text = family
            elif key == "android:letterSpacing":
                item.text = "0.01" if "Label" in name else "0.0"
        if weight:
            ET.SubElement(new, "item", name="android:textFontWeight").text = weight
        out.append(new)
    ET.indent(out, "    ")
    OUT.write_text('<?xml version="1.0" encoding="utf-8"?>\n'
                   "<!-- GENERATED by tools/gen_type.py from upstream's Material 3 type scale. Do not edit by hand. -->\n"
                   + ET.tostring(out, encoding="unicode") + "\n", encoding="utf-8")
    if not quiet:
        print(f"{len(out)} text appearances")
    return len(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", required=True, help="decoded upstream res dir")
    generate(ap.parse_args().base)


if __name__ == "__main__":
    main()
