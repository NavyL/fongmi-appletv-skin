"""Static checks on skin/res: well-formed, no duplicate resources, our own references resolve,
every layout keeps upstream's ids (integration, when a decoded APK is around)."""

import re
import xml.etree.ElementTree as ET
from pathlib import Path

import pytest

from conftest import ROOT, decoded_base
from check_ids import check_layouts

RES = ROOT / "skin" / "res"
A = "{http://schemas.android.com/apk/res/android}"
XMLS = sorted(RES.glob("**/*.xml"))


@pytest.mark.parametrize("path", XMLS, ids=lambda p: str(p.relative_to(RES)))
def test_xml_well_formed(path):
    ET.parse(path)


def test_no_duplicate_resource_names_within_values():
    for values_dir in RES.glob("values*"):
        seen = {}
        for f in values_dir.glob("*.xml"):
            for el in ET.parse(f).getroot():
                key = (el.tag, el.get("type", ""), el.get("name"))
                assert key not in seen, f"{key} defined in both {seen[key]} and {f.name}"
                seen[key] = f.name


def skin_resource_names():
    names = set()
    for d in RES.iterdir():
        kind = d.name.split("-")[0]
        if kind.startswith("values"):
            for f in d.glob("*.xml"):
                for el in ET.parse(f).getroot():
                    names.add((el.get("type") or el.tag, el.get("name")))
        else:
            for f in d.iterdir():
                stem = f.name.split(".")[0]
                names.add((kind, stem))
    return names


OWN_PREFIXES = ("tvos_", "gy_", "skin_")


def test_our_references_resolve():
    """Anything we reference with our own prefixes must exist in the skin (upstream can't provide it)."""
    names = skin_resource_names()
    ref = re.compile(r'@(?:android:)?(drawable|color|anim|animator|font|layout|style|dimen|string|mipmap|raw)/([A-Za-z0-9_.]+)')
    for path in XMLS:
        for kind, name in ref.findall(path.read_text(encoding="utf-8")):
            if name.startswith(OWN_PREFIXES):
                assert (kind, name) in names, f"{path.relative_to(RES)} references @{kind}/{name}, which the skin does not define"


def test_generated_files_carry_their_marker():
    for path in RES.glob("layout/*.xml"):
        head = path.read_text(encoding="utf-8")[:400]
        assert "GENERATED by tools/" in head or "as upstream" in head, f"{path.name}: say whether it is generated or hand-written (and keeps upstream ids)"


def test_brand_config():
    import json
    cfg = json.loads((ROOT / "skin" / "brand.json").read_text(encoding="utf-8"))
    assert re.fullmatch(r"[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+", cfg["package"])
    assert cfg["package"] != cfg["upstream_package"]
    assert (ROOT / "skin" / "assets" / cfg["ffalcon_card"]).exists()
    for d in ("values", "values-zh-rCN", "values-zh-rTW"):
        assert cfg["label"] in (RES / d / "strings_brand.xml").read_text(encoding="utf-8")


def test_font_family_files_exist():
    for fam in ("tvos_text", "tvos_display"):
        for font in ET.parse(RES / "font" / f"{fam}.xml").getroot():
            name = font.get(A + "font").split("/")[1]
            assert (RES / "font" / f"{name}.ttf").exists(), name


@pytest.mark.integration
def test_layouts_keep_upstream_ids():
    base = decoded_base()
    if base is None:
        pytest.skip("no decoded upstream APK under work/")
    assert check_layouts(RES, base) == []


@pytest.mark.integration
def test_patch_anchor_present_in_upstream_dex():
    base = decoded_base()
    if base is None:
        pytest.skip("no decoded upstream APK under work/")
    import patch_dex
    dex = base.parent / "classes.dex"
    assert patch_dex.OLD.encode() in dex.read_bytes(), "upstream changed Github.getReleases(); update patch_dex.OLD"
